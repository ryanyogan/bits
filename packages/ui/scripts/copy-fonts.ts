// Copies the self-hosted woff2 subsets the design system uses out of the
// @fontsource packages and regenerates src/styles/fonts.css.
//
// Run with `pnpm --filter @bits/ui fonts` after bumping a @fontsource package.
// The output is committed so the app never depends on node_modules layout (or
// Google Fonts) at runtime.
import * as fs from 'node:fs/promises'
import * as path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const packageDir = path.resolve(import.meta.dirname, '..')
const fontsDir = path.join(packageDir, 'src/fonts')
const cssFile = path.join(packageDir, 'src/styles/fonts.css')

interface Family {
  /** CSS font-family name. */
  family: string
  /** @fontsource package name. */
  pkg: string
  /** File prefix inside the package's files/ directory. */
  prefix: string
  weights: number[]
}

const families: Family[] = [
  { family: 'Unbounded', pkg: '@fontsource/unbounded', prefix: 'unbounded', weights: [500, 700, 800] },
  { family: 'Geist', pkg: '@fontsource/geist', prefix: 'geist', weights: [400, 500, 600] },
  { family: 'Geist Mono', pkg: '@fontsource/geist-mono', prefix: 'geist-mono', weights: [400, 500] },
]

// latin-ext first so latin (the common case) wins for overlapping code points.
const subsets = ['latin-ext', 'latin'] as const

await fs.rm(fontsDir, { recursive: true, force: true })
await fs.mkdir(fontsDir, { recursive: true })

let css = [
  '/* Generated by packages/ui/scripts/copy-fonts.ts. Do not edit by hand. */',
  '/* Fonts are licensed under the SIL Open Font License 1.1; see ../fonts/LICENSE-*.txt. */',
  '',
]

for (let { family, pkg, prefix, weights } of families) {
  let pkgDir = path.dirname(require.resolve(`${pkg}/package.json`))
  let unicode: Record<string, string> = JSON.parse(
    await fs.readFile(path.join(pkgDir, 'unicode.json'), 'utf8'),
  )
  await fs.copyFile(path.join(pkgDir, 'LICENSE'), path.join(fontsDir, `LICENSE-${prefix}.txt`))

  for (let weight of weights) {
    for (let subset of subsets) {
      let file = `${prefix}-${subset}-${weight}-normal.woff2`
      await fs.copyFile(path.join(pkgDir, 'files', file), path.join(fontsDir, file))
      css.push(
        '@font-face {',
        `  font-family: '${family}';`,
        '  font-style: normal;',
        '  font-display: swap;',
        `  font-weight: ${weight};`,
        `  src: url('../fonts/${file}') format('woff2');`,
        `  unicode-range: ${unicode[subset]};`,
        '}',
        '',
      )
    }
  }
}

await fs.writeFile(cssFile, css.join('\n'))
console.log(`Wrote ${path.relative(packageDir, cssFile)} and ${families.length} font families`)
