import type { Middleware } from 'remix/router'
import type { ScriptEntry } from 'remix/assets'

/**
 * Everything the app needs from the runtime it is running on. Two
 * implementations exist, selected by the `#platform` import condition in
 * package.json:
 *
 * - `platform.node.ts` (default): the Node dev server. Assets compile on
 *   demand through `remix/assets`; bindings come from wrangler's
 *   `getPlatformProxy()` so dev talks to the same local D1 as `wrangler dev`.
 * - `platform.worker.ts` (`workerd` condition): Cloudflare Workers. Assets
 *   were compiled by scripts/build.ts and are served by Workers Static
 *   Assets; bindings come from `cloudflare:workers`.
 */
export interface Platform {
  /** Which runtime this is. */
  runtime: 'node' | 'workerd'
  /** Cloudflare bindings and vars (types generated by `pnpm cf-typegen`). */
  env: Env
  assets: AppAssets
  /** How this runtime's Content-Security-Policy differs (decision 027). */
  csp: PlatformCsp
  /** Runtime-specific middleware that runs first (static files on Node). */
  middleware: Middleware
  /**
   * Finishes work after the response (or a cancelled stream) without
   * holding it up: `waitUntil` on Workers; on Node the promise just runs.
   */
  waitUntil(promise: Promise<unknown>): void
}

/**
 * The dev seam for the Content-Security-Policy. Production and tests enforce
 * the strict policy; only the HMR dev server relaxes it, because its browser
 * client adds import maps without a nonce and listens on another port.
 */
export interface PlatformCsp {
  /** Send `Content-Security-Policy-Report-Only` instead of enforcing. */
  reportOnly: boolean
  /** Extra `connect-src` sources (the HMR event stream). */
  connectSrc: string[]
}

/** The browser-facing asset surface the renderer and document need. */
export interface AppAssets {
  /** The browser runtime entry that boots hydration. */
  entry: ScriptEntry
  /** Global stylesheet URLs, in cascade order. */
  stylesheets: string[]
  /** Font URLs to preload. */
  fontPreloads: string[]
  /** Public URL of each self-hosted font, keyed by file name (`unbounded-latin-800-normal.woff2`). */
  fonts: Record<string, string>
  /** Resolves a `clientEntry(import.meta.url, ...)` module to its script entry. */
  getScriptEntry(entryId: string): Promise<ScriptEntry>
  /** Serves an `/assets/*` request, or null when this runtime does not serve assets itself. */
  fetch(request: Request): Promise<Response | null>
}

/** Build output consumed by the Worker: precomputed asset URLs. */
export interface AssetManifest {
  entry: ScriptEntry
  stylesheets: string[]
  fontPreloads: string[]
  fonts: Record<string, string>
  /** clientEntry module path (repo-relative, e.g. `packages/ui/src/app-bar-menu.tsx`) to its entry. */
  clientEntries: Record<string, ScriptEntry>
}
