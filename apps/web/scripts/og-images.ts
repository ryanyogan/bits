// `pnpm og`: makes the link-preview cards (decision 028).
//
// Starts the app on the test platform (in-memory D1 and R2 with every course
// in content/courses/ published), screenshots /cards/<name> at 1200×630 in
// headless Chromium (Playwright, a dev dependency; never in the Worker), and
// writes public/og/<name>.png plus app/ui/og-cards.generated.ts, the list of
// cards with a content hash for `?v=`. Commit both. Run it after adding a
// course or changing a course's title, cover or badge.
//
// NODE_ENV=test is set by the package script, before the platform loads.
import { createHash } from 'node:crypto'
import * as fs from 'node:fs/promises'
import * as http from 'node:http'
import type { AddressInfo } from 'node:net'
import * as path from 'node:path'

import { chromium } from 'playwright'
import { createRequestListener } from 'remix/node-fetch-server'

import { disposePlatform } from '#platform'

import { router } from '../app/router.ts'
import { routes } from '../app/routes.ts'
import { cardNames, cardPath, OG_HEIGHT, OG_WIDTH } from '../app/ui/og.ts'
import { listCourseFolders } from './lib/content-folder.ts'

const appDir = path.resolve(import.meta.dirname, '..')
const outDir = path.join(appDir, 'public/og')
const manifestFile = path.join(appDir, 'app/ui/og-cards.generated.ts')

let slugs = (await listCourseFolders()).map((dir) => path.basename(dir))
let names = cardNames(slugs)

let server = http.createServer(createRequestListener(router.fetch))
await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve))
let origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`
let browser = await chromium.launch()

try {
  let page = await browser.newPage({ viewport: { width: OG_WIDTH, height: OG_HEIGHT }, deviceScaleFactor: 1 })
  await fs.rm(outDir, { recursive: true, force: true })
  await fs.mkdir(outDir, { recursive: true })
  let hashes: Record<string, string> = {}
  for (let name of names) {
    let response = await page.goto(origin + routes.cards.show.href({ card: name }), { waitUntil: 'networkidle' })
    if (!response?.ok()) throw new Error(`/cards/${name} answered ${response?.status()}`)
    await page.evaluate(() => document.fonts.ready)
    let png = await page.locator('[data-og-card]').screenshot({ type: 'png' })
    await fs.writeFile(path.join(appDir, 'public', cardPath(name)), png)
    hashes[name] = createHash('sha256').update(png).digest('hex').slice(0, 10)
    console.log(`✓ ${cardPath(name)} (${Math.round(png.length / 1024)} KB)`)
  }
  let entries = Object.entries(hashes).map(([name, hash]) => `  '${name}': '${hash}',`)
  await fs.writeFile(
    manifestFile,
    [
      '// Generated by scripts/og-images.ts (`pnpm og`). Do not edit by hand.',
      "// Card name → first 10 hex of the PNG's SHA-256 (the `?v=` cache-buster).",
      'export const ogCards: Record<string, string> = {',
      ...entries,
      '}',
      '',
    ].join('\n'),
  )
  console.log(`Wrote ${names.length} cards and ${path.relative(appDir, manifestFile)}`)
} finally {
  await browser.close()
  server.close()
  server.closeAllConnections()
  await disposePlatform()
}
